def build():
    print("Building knowledge base (TF-IDF)...")
    os.makedirs(DATA_DIR, exist_ok=True)

    texts = [d["content"] for d in DOCUMENTS]
    sources = [d["source"] for d in DOCUMENTS]

    # 中文分词友好：char + word 混合
    vec = TfidfVectorizer(
        analyzer="char_wb",
        ngram_range=(2, 4),
        max_features=2000,
        max_df=0.9,
        min_df=1,
    )
    matrix = vec.fit_transform(texts)

    data = {
        "vectorizer": vec,
        "tfidf_matrix": matrix,
        "documents": texts,
        "sources": sources,
    }

    kb_path = os.path.join(DATA_DIR, "knowledge_base.pkl")
    with open(kb_path, "wb") as f:
        pickle.dump(data, f)

    print(f"  Done! {len(texts)} docs → {kb_path}")
    print(f"  TF-IDF vocab size: {len(vec.vocabulary_)}")


if __name__ == "__main__":
    build()
